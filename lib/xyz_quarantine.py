# -*- coding: utf-8 -*-
"""Карантин XYZ: скрипты и режимы, которые работают нестабильно.

Перед запуском такого скрипта показывается предупреждение «Продолжить?».
Выйти из карантина: убрать вызов xyz_quarantine.confirm(...) из скрипта, пометку
«⚠» из названия/подсказки и запись из списка ниже (+ хронология).
"""
import xyz_forms as forms

# имя на ленте / в меню -> что известно
LIST = {
    u"Без ноликов": u"не проверялся после последних правок",
    u"Этажи вразнос": u"не проверялся на рабочих моделях",
    u"IKEA": u"не проверялся на рабочих моделях",
    u"Умные выноски": u"марки ложатся «в космосе», с наложениями",
    u"Разнести наложенные": u"результат нестабилен",
    u"Обозвать": u"пишет наименования, количества и изоляцию во ВСЕЙ модели без выбора области и без пробы "
                 u"(жёстко: здание «Основной дом», запасы 1,05/1,1/1,2, изоляция ST AD 10). Переделывается: область, операции, таблица «было → станет»",
    u"Система отдельно": u"создаёт виды «db_Система_<имя>» и фильтры «db_НЕ_система_<имя>» без списка того, что будет создано; "
                         u"шаблон и фильтры подсветки зашиты в код. Переделывается",
    u"Автопилот": u"выключатель пересчёта марок-отметок на взрыв-схемах; окно не объясняет, что он делает и сколько стоит. Переделывается",
}


def confirm(name):
    """True - пользователь согласен запустить скрипт из карантина."""
    note = LIST.get(name, u"")
    msg = (u"⚠ «{}» в карантине — работает нестабильно и ещё обкатывается.\n\n"
           u"Результат может потребовать ручной правки. Перед массовым применением "
           u"проверьте на одном-двух элементах; отмена — Ctrl+Z.").format(name)
    if note:
        msg += u"\n\nПричина: " + note + u"."
    return bool(forms.alert(msg + u"\n\nЗапустить?", title=u"Карантин", yes=True, no=True))
